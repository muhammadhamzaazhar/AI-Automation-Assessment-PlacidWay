"""Run eval/cases.yaml against the real bot (OpenAI calls) and write TEST_RESULTS.md.

Usage:  python -m scripts.run_eval              # all cases
        python -m scripts.run_eval cost trick-price   # selected case ids
"""

import json
import logging
import sys
from dataclasses import asdict

import yaml

from app import factory
from app.chat.schemas import ChatTurn
from app.chat.service import ChatReply, ChatService
from app.config import PROJECT_ROOT, get_settings
from app.retrieval.embeddings import Embedder

CASES_FILE = PROJECT_ROOT / "eval" / "cases.yaml"
REPORT_FILE = PROJECT_ROOT / "TEST_RESULTS.md"
RAW_FILE = PROJECT_ROOT / "eval" / "results.json"


def run_case(service: ChatService, case: dict) -> tuple[list[tuple[str, ChatReply]], list[str]]:
    history: list[ChatTurn] = []
    transcript: list[tuple[str, ChatReply]] = []
    disclaimer_shown = False
    for turn in case["turns"]:
        reply = service.reply(turn, history, disclaimer_shown)
        disclaimer_shown = disclaimer_shown or reply.disclaimer is not None
        transcript.append((turn, reply))
        history += [ChatTurn(role="user", content=turn), ChatTurn(role="assistant", content=reply.answer)]
    return transcript, check(case.get("expect", {}), transcript[-1][1])


def check(expect: dict, reply: ChatReply) -> list[str]:
    """Return the list of failed checks (empty means pass)."""
    failures = []
    text = reply.answer.lower()
    urls = [s.url for s in reply.sources]

    if "intent" in expect and reply.intent != expect["intent"]:
        failures.append(f"intent is {reply.intent!r}, expected {expect['intent']!r}")
    if "answerable" in expect and reply.answerable != expect["answerable"]:
        failures.append(f"answerable is {reply.answerable}")
    if "quote_cta" in expect and reply.show_quote_cta != expect["quote_cta"]:
        failures.append(f"quote CTA is {reply.show_quote_cta}")
    if "has_sources" in expect and bool(urls) != expect["has_sources"]:
        failures.append("sources missing" if expect["has_sources"] else "unexpected sources")
    if "source_contains" in expect and not any(expect["source_contains"] in u for u in urls):
        failures.append(f"no source URL containing {expect['source_contains']!r}")
    for needle in expect.get("contains_all", []):
        if needle.lower() not in text:
            failures.append(f"answer lacks {needle!r}")
    if expect.get("contains_any") and not any(n.lower() in text for n in expect["contains_any"]):
        failures.append(f"answer lacks any of {expect['contains_any']}")
    for needle in expect.get("not_contains", []):
        if needle.lower() in text:
            failures.append(f"answer contains {needle!r}")
    if "standalone_contains" in expect and expect["standalone_contains"] not in (reply.standalone_question or "").lower():
        failures.append(f"rewritten question {reply.standalone_question!r} lacks {expect['standalone_contains']!r}")
    return failures


def write_report(records: list[dict], model: str) -> None:
    """Write TEST_RESULTS.md from the records saved in eval/results.json."""
    cases = {c["id"]: c for c in yaml.safe_load(CASES_FILE.read_text(encoding="utf-8"))}
    passed = sum(1 for r in records if not r["failures"])
    lines = [
        "# Test results",
        "",
        f"Generated by `python -m scripts.run_eval` with `{model}`. Checks passed: **{passed}/{len(records)}**.",
        "",
        "## Required test questions",
        "",
    ]
    required = [r for r in records if cases[r["id"]].get("required")]
    for number, record in enumerate(required, start=1):
        lines += [f"### {number}. {cases[record['id']]['type']}", ""]
        for turn in record["turns"]:
            lines += [f"**Q:** {turn['visitor']}", "", f"**A:** {turn['answer']}", ""]
            if turn["sources"]:
                links = ", ".join(f"[{s['title']}]({s['url']})" for s in turn["sources"])
                lines += [f"Source: {links}", ""]
        if record["failures"]:
            lines += [f"❌ Check failed: {'; '.join(record['failures'])}", ""]

    lines += ["## Extra test cases", "", "Full answers are in `eval/results.json`.", "",
              "| Question | Result |", "|---|---|"]
    for record in records:
        if not cases[record["id"]].get("required"):
            question = " → ".join(t["visitor"] for t in record["turns"]).replace("|", "\\|")
            result = "✅" if not record["failures"] else "❌ " + "; ".join(record["failures"])
            lines.append(f"| {question} | {result} |")

    REPORT_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    logging.basicConfig(level=logging.WARNING)
    sys.stdout.reconfigure(encoding="utf-8")
    settings = get_settings()
    client = factory.openai_client(settings)
    kb = factory.load_knowledge_base(settings, Embedder(client, settings.embedding_model))
    service = factory.chat_service(settings, client, kb, storage=None)

    cases = yaml.safe_load(CASES_FILE.read_text(encoding="utf-8"))
    if len(sys.argv) > 1:
        cases = [c for c in cases if c["id"] in sys.argv[1:]]

    records = []
    for case in cases:
        transcript, failures = run_case(service, case)
        records.append({"id": case["id"], "failures": failures,
                        "turns": [{"visitor": turn, **asdict(reply)} for turn, reply in transcript]})
        print(f"{'PASS' if not failures else 'FAIL'}  {case['id']:22} {'; '.join(failures)}")

    RAW_FILE.write_text(json.dumps(records, ensure_ascii=False, indent=1), encoding="utf-8")
    if len(sys.argv) == 1:  # only a full run rewrites the report
        write_report(records, settings.llm_model)
    failed = sum(1 for r in records if r["failures"])
    print(f"\n{len(records) - failed}/{len(records)} passed")
    return 0 if failed == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
